// Copilot's "how to write flight programs" guide (06 §6, WP-4b) has one source, docs/programs-guide.md; the
// system prompt reads it from electron/copilot/programs-guide.mjs, which this script generates so the bundled
// agent needs no file at run time.
//   node scripts/programs-guide.mjs           write electron/copilot/programs-guide.mjs
//   node scripts/programs-guide.mjs --check   fail when it is out of date (electron/test/programs-guide.test.mjs)
import fs from "node:fs";
import path from "node:path";

import { fail, log, ROOT } from "./lib.mjs";

const SOURCE = path.join(ROOT, "docs/programs-guide.md");
const TARGET = path.join(ROOT, "electron/copilot/programs-guide.mjs");

function render(markdown) {
  return (
    "// Generated by scripts/programs-guide.mjs from docs/programs-guide.md. Do not edit by hand.\n" +
    `export const PROGRAMS_GUIDE = ${JSON.stringify(markdown.trim())};\n`
  );
}

const wanted = render(fs.readFileSync(SOURCE, "utf8"));
if (process.argv.includes("--check")) {
  const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, "utf8") : "";
  if (current !== wanted) fail("electron/copilot/programs-guide.mjs is out of date: run node scripts/programs-guide.mjs");
  log("electron/copilot/programs-guide.mjs is current");
} else {
  fs.writeFileSync(TARGET, wanted);
  log("electron/copilot/programs-guide.mjs is ready");
}
