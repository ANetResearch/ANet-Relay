// Regenerates src/api/types.ts from src/api/schema.json (exported by the backend from its pydantic models,
// 03 §10.3) with json-schema-to-typescript. `--check` exits 1 when the committed file differs (CI drift gate).
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { compile } from 'json-schema-to-typescript'

const root = resolve(import.meta.dirname, '..')
const SCHEMA = resolve(root, 'src/api/schema.json')
const OUT = resolve(root, 'src/api/types.ts')

export const BANNER = `/* GENERATED by scripts/gen-types.mjs from src/api/schema.json (backend pydantic export, 03 §10.3). DO NOT EDIT.
 * Run \`npm run types\` after the backend schema changes; src/api/types.test.ts fails when this file drifts.
 * Application code imports from '@/api' (index.ts) and uses indexed access types for nested shapes. */`

/** Compiles the schema into the text of types.ts. */
export async function generate(schema) {
  const body = await compile(schema, 'RelaySchema', {
    bannerComment: BANNER,
    additionalProperties: false,
    unreachableDefinitions: true,
    strictIndexSignatures: true,
    style: { singleQuote: true, semi: false, printWidth: 120 },
  })
  return body
}

async function main() {
  if (!existsSync(SCHEMA)) {
    console.error('src/api/schema.json does not exist yet; src/api/types.ts stays hand-written (03 §10.3).')
    process.exit(process.argv.includes('--check') ? 0 : 1)
  }
  const out = await generate(JSON.parse(readFileSync(SCHEMA, 'utf8')))
  if (process.argv.includes('--check')) {
    const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
    if (cur !== out) {
      console.error('src/api/types.ts is out of date with schema.json; run `npm run types`.')
      process.exit(1)
    }
    return
  }
  writeFileSync(OUT, out)
  console.log(`wrote ${OUT}`)
}

if (import.meta.url === `file://${process.argv[1]}`) await main()
