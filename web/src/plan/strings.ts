export function translatePlan(lang: Lang, key: PlanKey, params?: Params): string {
  return format((lang === 'zh' ? zh : en)[key], params)
}

export function usePT(): (key: PlanKey, params?: Params) => string {
  const lang = useLang()
  return useCallback((key: PlanKey, params?: Params) => translatePlan(lang, key, params), [lang])
}

