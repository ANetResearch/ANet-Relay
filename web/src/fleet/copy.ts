export const DICTS8: Record<Lang, Record<Key8, string>> = { en: en8, zh: zh8 }

export type AnyKey = MessageKey | Key8

const isKey8 = (k: string): k is Key8 => k in en8

export function translate8(lang: Lang, key: AnyKey, params?: Params): string {
  if (isKey8(key)) return format(DICTS8[lang][key] ?? en8[key], params)
  return translate(lang, key, params)
}

/** Non-hook lookup in the current language. */
export function t8(key: AnyKey, params?: Params): string {
  return translate8(useLangStore.getState().lang, key, params)
}

export function useT8(): (key: AnyKey, params?: Params) => string {
  const lang = useLang()
  return useCallback((key: AnyKey, params?: Params) => translate8(lang, key, params), [lang])
}
