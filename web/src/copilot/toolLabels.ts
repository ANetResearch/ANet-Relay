/** Name for a tool id in a language; unknown ids are shown as they are. */
export function toolLabel(tool: string, lang: Lang = useLangStore.getState().lang): string {
  const l = TOOL_LABELS[tool]
  return l ? (lang === 'zh' ? l[1] : l[0]) : tool
}
