export const COPILOT_DICTS: Record<Lang, Record<CopilotKey, string>> = { en, zh }

export function translateCopilot(lang: Lang, key: CopilotKey, params?: Params): string {
  return format(COPILOT_DICTS[lang][key] ?? en[key] ?? key, params)
}

export function cpt(key: CopilotKey, params?: Params): string {
  return translateCopilot(useLangStore.getState().lang, key, params)
}

export function useCPT(): (key: CopilotKey, params?: Params) => string {
  const lang = useLang()
  return useCallback((key: CopilotKey, params?: Params) => translateCopilot(lang, key, params), [lang])
}
