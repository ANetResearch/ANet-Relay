export const LAB_DICTS: Record<Lang, Record<LabKey, string>> = { en, zh }

export function translateLab(lang: Lang, key: LabKey, params?: Params): string {
  return format(LAB_DICTS[lang][key] ?? en[key] ?? key, params)
}

/** Non-hook lookup in the current language (stores, toasts). */
export function tL(key: LabKey, params?: Params): string {
  return translateLab(useLangStore.getState().lang, key, params)
}

export function useTL(): (key: LabKey, params?: Params) => string {
  const lang = useLang()
  return useCallback((key: LabKey, params?: Params) => translateLab(lang, key, params), [lang])
}

/** Is this a reason code the Lab can name? */
export const reasonKey = (code: string | null | undefined): LabKey | null =>
  code && `lab.reason.${code}` in en ? (`lab.reason.${code}` as LabKey) : null
