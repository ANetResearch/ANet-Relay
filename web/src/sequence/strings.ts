const TABLE: Record<Lang, Record<SeqKey, string>> = { en, zh }

export function translateSeq(lang: Lang, key: SeqKey, params?: Params): string {
  return format(TABLE[lang][key] ?? en[key], params)
}

export function useST(): (key: SeqKey, params?: Params) => string {
  const lang = useLang()
  return useCallback((key: SeqKey, params?: Params) => translateSeq(lang, key, params), [lang])
}

