export const TWIN_DICTS: Record<Lang, Record<TwinKey, string>> = { en, zh }

export function translateTwin(lang: Lang, key: TwinKey, params?: Params): string {
  return format(TWIN_DICTS[lang][key] ?? en[key] ?? key, params)
}

/** Non-hook lookup in the current language (actions, toasts). */
export function tt(key: TwinKey, params?: Params): string {
  return translateTwin(useLangStore.getState().lang, key, params)
}

export function useTT(): (key: TwinKey, params?: Params) => string {
  const lang = useLang()
  return useCallback((key: TwinKey, params?: Params) => translateTwin(lang, key, params), [lang])
}
